"""Build the additive-duration concept set from the pinned FASB 2026 US-GAAP schema.

    uv run python scripts/build_us_gaap_types.py [--xsd PATH] [--out PATH]

CON-06 (``T-150``) tests only concepts whose sub-periods "sum to" the aggregated period, i.e.
amounts that add. The load-bearing source is the taxonomy element definitions (B6): an element is
an *additive duration amount* when the FASB 2026 schema declares it
``type='xbrli:monetaryItemType'`` (an amount, not shares / a per-share ratio / a percentage) with
``xbrli:periodType='duration'`` (a flow). ``WeightedAverageNumberOfDilutedSharesOutstanding`` is
``xbrli:sharesItemType``, so it is excluded.

The default ``--xsd`` is the pinned zip extract; the default ``--out`` is a tracked data file the
gate loads at run time (so the gate works where the schema extract is absent, e.g. CI). The header
records the source path, its sha256 and the counts, so the file is auditable against the schema.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DEFAULT_XSD = Path("/workspaces/thesis/scratch/t148b/fasb2026/us-gaap-2026/elts/us-gaap-2026.xsd")
DATA = REPO / "src" / "fundamental_agent" / "data"
DEFAULT_ALL = DATA / "us_gaap_2026_elements.txt"
DEFAULT_ADDITIVE = DATA / "us_gaap_2026_duration_monetary.txt"

_ELEMENT_RE = re.compile(r"<xs:element\s(?P<attrs>[^>]*?)/>")
_ID_RE = re.compile(r"id='([^']*)'")
_TYPE_RE = re.compile(r"type='([^']*)'")
_PERIOD_RE = re.compile(r"xbrli:periodType='([^']*)'")
MONETARY = "xbrli:monetaryItemType"


def schema_ids(xsd: Path) -> tuple[list[str], list[str], int, int]:
    """``(all ids, additive-duration ids, monetary count, duration count)`` of the schema.

    An *additive duration amount* is ``type='xbrli:monetaryItemType'`` (an amount, not shares / a
    per-share ratio / a percentage) with ``xbrli:periodType='duration'`` (a flow)."""
    text = xsd.read_text(encoding="utf-8")
    all_ids: set[str] = set()
    additive: set[str] = set()
    monetary = duration = 0
    for match in _ELEMENT_RE.finditer(text):
        attrs = match.group("attrs")
        id_match = _ID_RE.search(attrs)
        if id_match is None:
            continue
        element_id = id_match.group(1)
        all_ids.add(element_id)
        type_match = _TYPE_RE.search(attrs)
        period_match = _PERIOD_RE.search(attrs)
        is_monetary = type_match is not None and type_match.group(1) == MONETARY
        is_duration = period_match is not None and period_match.group(1) == "duration"
        if is_monetary:
            monetary += 1
        if is_duration:
            duration += 1
        if is_monetary and is_duration:
            additive.add(element_id)
    return sorted(all_ids), sorted(additive), monetary, duration


def _write(  # noqa: PLR0913, PLR0917 - one data file's header and ids
    path: Path, title: str, source: str, sha: str, extra: list[str], ids: list[str]
) -> None:
    header = [
        f"# {title}",
        "# Generated by scripts/build_us_gaap_types.py; do not edit by hand.",
        f"# source: {source}",
        f"# sha256: {sha}",
        *[f"# {line}" for line in extra],
        f"# elements: {len(ids)}",
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join([*header, *ids]) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--xsd", type=Path, default=DEFAULT_XSD)
    parser.add_argument("--out-all", type=Path, default=DEFAULT_ALL)
    parser.add_argument("--out-additive", type=Path, default=DEFAULT_ADDITIVE)
    args = parser.parse_args(argv)
    all_ids, additive, monetary, duration = schema_ids(args.xsd)
    sha = hashlib.sha256(args.xsd.read_bytes()).hexdigest()
    counts = [
        f"monetaryItemType elements: {monetary}; periodType='duration' elements: {duration}",
    ]
    _write(
        args.out_all,
        "FASB 2026 US-GAAP schema element ids (every declared element).",
        str(args.xsd),
        sha,
        counts,
        all_ids,
    )
    _write(
        args.out_additive,
        "FASB 2026 US-GAAP additive-duration concepts, for CON-06 (T-150).",
        str(args.xsd),
        sha,
        counts,
        additive,
    )
    print(
        f"{len(all_ids)} elements, {len(additive)} additive-duration -> {args.out_additive} "
        f"(from {args.xsd})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
