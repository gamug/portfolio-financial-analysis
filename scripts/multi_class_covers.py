"""T-071 part 2b (D5): the current members' cover-page **common classes**.

    uv run python scripts/multi_class_covers.py [--db PATH] [--out FILE]

Read-only. For each **current** member's newest 10-K it reads the cover page's per-class common
shares outstanding (``filing_cover_shares``) and reports the classes ``kg_schema.market_cap`` counts.
MKT-03's multi-class company has **more than one class of common stock outstanding**, listed or not
("unlisted share class lines are included"); a registered note, debenture, preferred or depositary
share is not a class (C6 p.9, C11). The profile's multi-class overlay is ``n_common_classes > 1``,
which ``scripts/build_company_profile.py`` applies.

The checklist's ``company_types.csv`` counts **every** listed security on the cover, which is why 75
current rows carried ``multi_class_listed = True`` (JPM, BAC, DUK, SO, NEE, T and others whose extra
tickers are notes and preferred series). The leavers keep `T-153` part 3b's evidence
(``docs/leaver_company_types.csv``'s ``cover_classes`` -- the same rule, from the cover page of the
last 10-K on or before the exit); this measurement is the current members' own.

The output is committed (``docs/multi_class_covers.csv``), one row per cover entry, so the list is
reproducible from the repo. It is **not** read by the tests or the runtime.
"""

from __future__ import annotations

import argparse
import csv
import io
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from portfolio_common.db import Database  # noqa: E402

from kg_schema.company_profile import profiles  # noqa: E402
from kg_schema.market_cap import cover_total  # noqa: E402

DEFAULT_DB = "/workspaces/thesis/data/financial.db"
DEFAULT_OUT = REPO / "docs" / "multi_class_covers.csv"
COLUMNS = (
    "cik",
    "ticker",
    "accession",
    "period_end",
    "available_at",
    "class_member",
    "value",
    "as_of_date",
    "n_common_classes",
    "multi_class",
)
HEADER = (
    "# Generated by scripts/multi_class_covers.py -- the current members' newest 10-K cover page.",
    "# The classes kg_schema.market_cap counts (MKT-03: more than one class of COMMON stock; a note,",
    "# preferred or depositary series is not one). multi_class = n_common_classes > 1.",
    "# One row per cover entry; the leavers keep docs/leaver_company_types.csv's cover_classes.",
)


def measure(db_path: str) -> list[dict[str, Any]]:
    """One row per cover entry of each current member's newest 10-K."""
    conn = Database.connect(db_path, read_only=True)
    out: list[dict[str, Any]] = []
    for cik, profile in sorted(profiles().items()):
        if profile.valid_to:  # a leaver keeps part 3b's evidence
            continue
        filing = conn.execute(
            """
            SELECT f.id, f.accession_number, f.period_end, f.available_at
            FROM sec_filings f JOIN assets a ON a.id = f.asset_id
            WHERE a.cik = ? AND f.form LIKE '10-K%' AND f.period_end IS NOT NULL
            ORDER BY f.period_end DESC, f.available_at DESC, f.id DESC
            LIMIT 1
            """,
            (cik,),
        ).fetchone()
        if filing is None:
            continue
        entries = list(
            conn.execute(
                "SELECT class_member, value, as_of_date FROM filing_cover_shares "
                "WHERE filing_id = ? ORDER BY id",
                (int(filing["id"]),),
            )
        )
        if not entries:
            continue
        total = cover_total(
            [(str(e["class_member"]), float(e["value"]), str(e["as_of_date"])) for e in entries],
            cik=cik,
        )
        n_classes = total.n_classes if total is not None else 0
        for entry in entries:
            out.append(
                {
                    "cik": cik,
                    "ticker": profile.ticker,
                    "accession": filing["accession_number"] or "",
                    "period_end": filing["period_end"],
                    "available_at": filing["available_at"],
                    "class_member": entry["class_member"] or "(total)",
                    "value": f"{float(entry['value']):.0f}",
                    "as_of_date": entry["as_of_date"],
                    "n_common_classes": n_classes,
                    "multi_class": n_classes > 1,
                }
            )
    conn.close()
    return out


def render(rows: list[dict[str, Any]]) -> str:
    buffer = io.StringIO()
    for line in HEADER:
        buffer.write(line + "\n")
    writer = csv.DictWriter(buffer, fieldnames=COLUMNS, lineterminator="\n")
    writer.writeheader()
    for row in rows:
        writer.writerow(row)
    return buffer.getvalue()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--db", default=DEFAULT_DB)
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()
    rows = measure(args.db)
    Path(args.out).write_text(render(rows))
    flagged = sorted({r["cik"] for r in rows if r["multi_class"]})
    print(f"wrote {args.out}: {len(rows)} cover entries, {len({r['cik'] for r in rows})} companies")
    print(f"  multi-class (more than one common class): {len(flagged)}")
    print(f"  one common class: {len({r['cik'] for r in rows}) - len(flagged)}")


if __name__ == "__main__":
    main()
