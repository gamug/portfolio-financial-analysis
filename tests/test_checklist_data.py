"""The generated checklist data files (T-076, D1).

Reads only tracked files: ``src/fundamental_agent/data/metric_definitions.csv`` and
``checklist_rules.csv``, both generated by ``scripts/build_metric_dictionary.py`` from checklist v1.3,
plus the generated ``docs/metric_dictionary.md``. ``docs/checklist_sec/`` is git-excluded and local
only, so neither the tests nor the runtime may read it.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DATA = REPO / "src" / "fundamental_agent" / "data"
DEFINITIONS = DATA / "metric_definitions.csv"
RULES = DATA / "checklist_rules.csv"
DICTIONARY = REPO / "docs" / "metric_dictionary.md"

# The checklist's own counts (v1.3, "Totals"): 78 rules, 11 declared limitations, 5 calibrated
# screens, 39 Annex B metric rows.
RULE_LAYERS = ("ID", "PER", "CON", "DQ", "MET", "MKT", "APP")
RULE_ROWS = 78
LIMITATIONS = 11
SCREENS = 5
DICTIONARY_ROWS = 39


def _csv(path: Path) -> list[dict[str, str]]:
    with path.open() as handle:
        return list(csv.DictReader(handle))


def _dictionary() -> list[dict[str, str]]:
    """The generated dictionary's Annex B rows, in row order."""
    rows = []
    for line in DICTIONARY.read_text().splitlines():
        if not line.startswith("| MD-"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        rows.append({"id": cells[0], "metric": cells[1], "formula": cells[3], "basis": cells[4]})
    return rows


def _same(first: str, second: str) -> bool:
    """Whether two cells say the same thing: markdown emphasis, code spans and whitespace ignored."""
    return re.sub(r"[\s`*\\]", "", first) == re.sub(r"[\s`*\\]", "", second)


def test_the_definitions_agree_with_the_dictionary_row_by_row() -> None:
    dictionary = _dictionary()
    definitions = _csv(DEFINITIONS)
    assert len(dictionary) == len(definitions) == DICTIONARY_ROWS
    for generated, row in zip(definitions, dictionary, strict=True):
        assert generated["md_id"] == row["id"]
        assert generated["metric"] == row["metric"].strip("`")
        assert _same(generated["formula"], row["formula"])
        assert _same(generated["basis"], row["basis"])


def test_the_rule_file_has_the_checklists_counts() -> None:
    rules = _csv(RULES)
    layers: dict[str, int] = {}
    for row in rules:
        assert row["layer"] in (*RULE_LAYERS, "L", "A", "MD"), row
        assert row["id"].startswith(f"{row['layer']}-"), row
        assert row["rule"].strip(), row
        layers[row["layer"]] = layers.get(row["layer"], 0) + 1
    assert sum(layers[layer] for layer in RULE_LAYERS) == RULE_ROWS
    assert layers["L"] == LIMITATIONS
    assert layers["A"] == SCREENS
    assert layers["MD"] == DICTIONARY_ROWS


def test_every_rule_id_is_unique() -> None:
    ids = [row["id"] for row in _csv(RULES)]
    assert len(ids) == len(set(ids)) == RULE_ROWS + LIMITATIONS + SCREENS + DICTIONARY_ROWS
