REPO = Path(__file__).resolve().parents[1]
DICTIONARY = REPO / "docs" / "metric_dictionary.md"
MATRIX = REPO / "src" / "kg_schema" / "data" / "applicability_matrix.csv"
G = "us-gaap_"
KEY = "2024-12-31 (FY)"
PRIOR = "2023-12-31 (FY)"
# the AAPL fixture's own fiscal years (its 10-K is FY2023, so its columns are not KEY/PRIOR)
AA_KEY = "2023-09-30 (FY)"
AA_PRIOR = "2022-09-24 (FY)"

# The building-block rows of Annex B: the helper that computes each (D13 (a)).
BUILDING_BLOCK_IMPL: dict[str, Any] = {
    "ebitda": leverage.compute,
    "invested capital": capital_metrics.invested_capital,
    "net debt": capital_metrics.net_debt,
    "free cash flow": cashflow.free_cash_flow,
}
# Annex B rows computed outside fundamental_agent (the VALORIZATION metric is cycle's).
OUTSIDE_IMPL = {"earnings_yield": "cycle.scores.valorization (Annex B marks it VALORIZATION)"}
# The computed metrics Annex B does not cover: each with the reason it is allowed.
ALLOWLIST = {
    "return_on_invested_capital_effective_rate": (
        "T-151 part 2 (D3) robustness metric; Annex B was frozen before it, and it is a variant of "
        "MD-11 (ROIC at the filing's own effective rate), not a new formula."
    ),
}


def _dictionary_metrics() -> dict[str, dict[str, str]]:
    """``{metric: {id, kind, basis, formula}}`` from the generated dictionary."""
    rows: dict[str, dict[str, str]] = {}
    for line in DICTIONARY.read_text().splitlines():
        if not line.startswith("| MD-"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        metric = cells[1].strip("`")
        rows[metric] = {"id": cells[0], "kind": cells[2], "basis": cells[4], "formula": cells[3]}
    return rows


def _matrix() -> list[dict[str, str]]:
    with MATRIX.open() as handle:
        return list(csv.DictReader(handle))


def _computed_metric_names(stmts: Statements) -> set[str]:
    names: set[str] = set()
    for _group, compute in COMPUTERS.items():
        for result in compute(stmts, KEY, PRIOR, None):
            names.add(result.name)
    for result in valuation.compute(stmts, KEY):
        names.add(result.name)
    return names


@pytest.fixture
def _aapl(aapl_10k: Statements) -> Statements:
    return aapl_10k


# -- (a) every dictionary metric has an implementation ----------------------------------------------


def test_every_dictionary_metric_has_an_implementation(_aapl: Statements) -> None:
    computed = _computed_metric_names(_aapl)
    missing = [
        metric
        for metric in _dictionary_metrics()
        if metric not in computed
        and metric not in BUILDING_BLOCK_IMPL
        and metric not in OUTSIDE_IMPL
    ]
    assert missing == [], f"dictionary metrics with no implementation: {missing}"
    # every declared implementation is callable
    for name, impl in BUILDING_BLOCK_IMPL.items():
        assert callable(impl), name


# -- (b) every computed metric has a dictionary row -------------------------------------------------


def test_every_computed_metric_has_a_dictionary_row(_aapl: Statements) -> None:
    computed = _computed_metric_names(_aapl)
    dictionary = _dictionary_metrics()
    undocumented = computed - set(dictionary) - set(ALLOWLIST)
    assert undocumented == set(), f"computed metrics with no dictionary row: {sorted(undocumented)}"
    # the allowlist is exactly the metrics Annex B does not cover
    assert set(ALLOWLIST) == {"return_on_invested_capital_effective_rate"}


def test_the_provenance_declaration_covers_every_computed_metric(_aapl: Statements) -> None:
    computed = _computed_metric_names(_aapl)
    assert computed == set(provenance.ITEMS), (
        f"provenance.ITEMS differs from the computed metrics: "
        f"{sorted(computed ^ set(provenance.ITEMS))}"
    )
    assert computed == set(provenance.RULE_IDS)


# -- (c) every resolver map or tier has a rule ID ---------------------------------------------------


def test_every_resolver_map_has_a_rule_id() -> None:
    missing = [name for name in RESOLVER_MAPS if name not in RESOLVER_RULE_IDS]
    assert missing == [], f"resolver maps with no rule ID: {missing}"
    for name, rules in RESOLVER_RULE_IDS.items():
        assert rules, f"{name} has an empty rule-ID tuple"


# -- (d) the matrix and the code agree where the code can know the company type today ----------------


def test_the_matrix_is_complete_and_cites_a_rule() -> None:
    rows = _matrix()
    assert len(rows) == 35 * 6  # 35 metrics x 6 company types (the checklist's count)
    metrics = {r["metric"] for r in rows}
    assert len(metrics) == 35
    for row in rows:
        assert row["code"] in {"A", "ADJ", "NA"}, row
        if row["code"] != "A":
            assert row["rule"], f"{row} has a non-A code and no rule"
    # all six company-type columns are present with their cells, and the code applies every one of
    # them (T-071 part 1, P5: the comprehensive test below replaced the "cells the code can know
    # today" subset, which was the REIT and negative-equity cells only).
    for column in applicability.COLUMNS:
        assert sum(1 for r in rows if r["company_type"] == column) == 35


# -- (d) the matrix and the code agree on every cell (T-071 part 1, P5) -----------------------------

# The six matrix columns, each with the profile that activates it, and an operating company (which
# activates none). The negative-equity column is not a profile field: the metrics evaluate it from the
# filing (APP-07), so its case is a negative-equity payload.
_PROFILE_CASES: dict[str, tuple[str, bool, bool, bool]] = {
    "art_9_filer": ("article_9", False, False, False),
    "art_7_insurer": ("article_7", False, False, False),
    "other_financial": ("other_financial", False, False, False),
    "reit": ("operating", True, False, False),
    "negative_equity": ("operating", False, False, True),
    "multi_class": ("operating", False, True, False),
    "operating": ("operating", False, False, False),
}


def _company_profile(kind: str, *, reit: bool = False, multi_class: bool = False) -> CompanyProfile:
    return CompanyProfile(
        cik="0000000000",
        ticker="TEST",
        company_name="Test Co",
        type=kind,
        financial_firm=kind in {"article_9", "article_7", "other_financial"},
        reit=reit,
        multi_class=multi_class,
        regulated_utility=False,
        sector=None,
        sub_industry=None,
        evidence_accession="0000000000-26-000001",
        valid_from="2020-01-01",
        valid_to="",
    )


def _computed(
    stmts: Statements, period_key: str = AA_KEY, prior_key: str | None = AA_PRIOR
) -> list[tuple[str, MetricResult]]:
    """Every metric the code computes for one filing, the way ``_compute_all`` gathers them."""
    out = [
        (group, result)
        for group, compute in COMPUTERS.items()
        for result in compute(stmts, period_key, prior_key, None)
    ]
    out += [(valuation.GROUP, result) for result in valuation.compute(stmts, period_key)]
    return out


def _values(results: list[tuple[str, MetricResult]]) -> dict[str, float | None]:
    return {result.name: result.value for _group, result in results}


def _negative_equity_stmts(aapl: Statements) -> Statements:
    """The same filing with every equity row's sign flipped: APP-07's condition comes from the filing."""
    payload = {
        key: [dict(row) for row in (aapl.raw.get(key) or [])]
        for key in ("income_statement", "balance_sheet", "cash_flow")
    }
    for row in payload["balance_sheet"]:
        if "Equity" in str(row.get("concept") or ""):
            for column, value in list(row.items()):
                # only the period columns (never `level`, `weight` or `preferred_sign`)
                if column[:4].isdigit() and isinstance(value, (int, float)):
                    row[column] = -abs(float(value))
    return Statements.from_payload(payload)


def test_every_matrix_cell_is_applied_by_the_code(_aapl: Statements) -> None:
    """For each of the six company-type columns, plus an operating company, the code empties, flags
    or keeps each metric exactly as its matrix cell says (P5)."""
    matrix = {(r["metric"], r["company_type"]): (r["code"], r["rule"]) for r in _matrix()}
    metrics = sorted({r["metric"] for r in _matrix()})
    assert len(metrics) == 35
    for column, (kind, reit, multi_class, negative) in _PROFILE_CASES.items():
        profile = _company_profile(kind, reit=reit, multi_class=multi_class)
        stmts = _negative_equity_stmts(_aapl) if negative else _aapl
        before = _values(_computed(stmts))
        results = _computed(stmts)
        apply_applicability(results, profile)
        after = _values(results)
        inputs = {result.name: result.inputs for _group, result in results}
        for metric in metrics:
            if metric not in after:
                # `earnings_yield` is VALORIZATION: `cycle` computes it, so its cell is applied in
                # T-071 part 2 (Annex B marks the row VALORIZATION). The matrix lookup still covers it.
                assert metric == "earnings_yield", (column, metric)
                continue
            code, rule = matrix[(metric, column)] if column in applicability.COLUMNS else ("A", "")
            own = inputs[metric]
            if code == "NA":
                assert after[metric] is None, (column, metric)
                assert own[f"flag_{metric}_not_applicable"] == 1.0, (column, metric)
                assert own["applicability_rule"] == rule, (column, metric)
            elif code == "ADJ":
                assert after[metric] == before[metric], (column, metric)
                assert own[f"flag_{metric}_adj"] == 1.0, (column, metric)
                assert own["applicability_rule"] == rule, (column, metric)
            else:
                assert after[metric] == before[metric], (column, metric)
                assert f"flag_{metric}_not_applicable" not in own, (column, metric)
                assert f"flag_{metric}_adj" not in own, (column, metric)
                assert "applicability_rule" not in own, (column, metric)
        # the lookup itself answers every one of the 35 metrics on this column
        for metric in metrics:
            code, rule = matrix[(metric, column)] if column in applicability.COLUMNS else ("A", "")
            assert applicability.applicability(metric, profile, negative_equity=negative) == (
                code,
                rule,
            ), (column, metric)


def test_the_metrics_the_matrix_does_not_cover_are_left_alone(_aapl: Statements) -> None:
    """The matrix has no row for `ebitda` (a building block) or the robustness ROIC variant: the layer
    makes no claim on them (declared in `docs/model_fixes.md`, T-071 part 1)."""
    uncovered = {"ebitda", "return_on_invested_capital_effective_rate"}
    assert uncovered & set(applicability.metrics()) == set()
    before = _values(_computed(_aapl))
    results = _computed(_aapl)
    apply_applicability(results, _company_profile("article_9"))
    after = _values(results)
    for metric in uncovered:
        assert after[metric] == before[metric], metric


def test_an_unknown_profile_is_flagged_never_guessed(_aapl: Statements) -> None:
    """P4: a CIK with no profile computes every metric and flags `company_type_unknown`."""
    before = _values(_computed(_aapl))
    results = _computed(_aapl)
    apply_applicability(results, None)
    for _group, result in results:
        assert result.value == before[result.name], result.name
        assert result.inputs[f"flag_{result.name}_company_type_unknown"] == 1.0, result.name


def test_compute_all_applies_the_matrix_for_a_known_company(_aapl: Statements) -> None:
    """P4: `_compute_all` is the one place the matrix is applied, and the empty reason reads it."""
    wells = profile_as_of("0000072971")
    assert wells is not None and wells.type == "article_9"
    analyst = FundamentalAnalyst(None, "rule-based")
    ctx = FilingContext(
        "WFC", "Wells Fargo", "10-K", "FY2023", _aapl, AA_KEY, AA_PRIOR, cik="0000072971"
    )
    article9 = {result.name: result for _group, result in analyst._compute_all(ctx)}
    gross = article9["gross_margin"]
    assert gross.value is None
    assert gross.inputs["flag_gross_margin_not_applicable"] == 1.0
    assert gross.inputs["provenance"]["empty_reason"] == "not_applicable"
    assert gross.inputs["provenance"]["applicability_rule"] == "APP-01"

    apple_ctx = FilingContext(
        "AAPL", "Apple", "10-K", "FY2023", _aapl, AA_KEY, AA_PRIOR, cik="0000320193"
    )
    operating = {result.name: result for _group, result in analyst._compute_all(apple_ctx)}
    assert operating["gross_margin"].value is not None
    assert "flag_gross_margin_not_applicable" not in operating["gross_margin"].inputs
    assert operating["gross_margin"].inputs["provenance"]["empty_reason"] is None


def test_nopat_taxes_a_reit_at_its_own_effective_rate() -> None:
    # F1: nopat_tax_rate takes the flow it taxes plus that basis's tax and pre-tax income
    rate, reason = nopat_tax_rate(100.0, reit=True, tax=20.0, pretax=120.0)
    assert reason == "reit_effective"
    assert rate != pytest.approx(0.21)
    rate, reason = nopat_tax_rate(100.0, reit=False, tax=20.0, pretax=120.0)
    assert reason == "statutory_21"
    assert rate == pytest.approx(0.21)


def test_enterprise_fcf_yield_is_empty_on_an_unclassified_balance_sheet() -> None:
    # MD-38's note: no classified balance sheet. The code empties it on a REIT-shaped payload
    # (no AssetsCurrent / LiabilitiesCurrent). The matrix cell itself (reit: NA) is applied by
    # `test_every_matrix_cell_is_applied_by_the_code`.
    stmts = _payload(classified=False)
    out = {r.name: r.value for r in valuation.compute(stmts, KEY)}
    assert out["enterprise_fcf_yield"] is None


def _payload(
    *, prior_equity: float = 400.0, equity: float = 450.0, classified: bool = True
) -> Statements:
    def row(concept: str, label: str, **periods: float) -> dict[str, Any]:
        return {
            "concept": concept,
            "label": label,
            "standard_concept": None,
            "abstract": False,
            "dimension": False,
            **periods,
        }

    balance = [
        row(G + "Assets", "Assets", **{"2024-12-31": 1_100.0, "2023-12-31": 1_000.0}),
        row(
            G + "StockholdersEquity", "Equity", **{"2024-12-31": equity, "2023-12-31": prior_equity}
        ),
        row(G + "LongTermDebt", "Debt", **{"2024-12-31": 210.0, "2023-12-31": 200.0}),
        row(
            G + "CashAndCashEquivalentsAtCarryingValue",
            "Cash",
            **{"2024-12-31": 60.0, "2023-12-31": 50.0},
        ),
    ]
    if classified:
        balance += [
            row(
                G + "AssetsCurrent", "Current assets", **{"2024-12-31": 300.0, "2023-12-31": 280.0}
            ),
            row(
                G + "LiabilitiesCurrent",
                "Current liabilities",
                **{"2024-12-31": 150.0, "2023-12-31": 140.0},
            ),
        ]
    return Statements.from_payload(
        {
            "income_statement": [
                row(G + "OperatingIncomeLoss", "Operating income", **{KEY: 100.0}),
                row(G + "NetIncomeLoss", "Net income", **{KEY: 80.0}),
                row(
                    G
                    + "IncomeLossFromContinuingOperationsBeforeIncomeTaxesExtraordinaryItemsNoncontrollingInterest",
                    "Pretax",
                    **{KEY: 120.0},
                ),
                row(G + "IncomeTaxExpenseBenefit", "Income tax", **{KEY: 20.0}),
            ],
            "balance_sheet": balance,
            "cash_flow": [],
        }
    )


